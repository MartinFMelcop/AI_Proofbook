#!/usr/bin/env python3
"""Measure physical RGBA silhouettes for rendering alignment, NEVER approve art or change pixels."""
from pathlib import Path
from PIL import Image
import hashlib, json
import numpy as np

ROOT=Path(__file__).resolve().parents[1]
assets={}
for building in ('cottage','forge','apothecary'):
    for view in range(4):
        path=ROOT/'site/assets/world'/f'r11_{building}_{view}.webp'
        im=Image.open(path).convert('RGBA')
        if im.size!=(640,640): raise ValueError((path,im.size))
        alpha=np.array(im.getchannel('A'))
        yy,xx=np.where(alpha>24)
        if len(xx)<10000:raise ValueError(f'no valid silhouette: {path}')
        x0,x1,y0,y1=[int(v) for v in (xx.min(),xx.max(),yy.min(),yy.max())]
        if y1<570:raise ValueError(f'unexpected missing ground base: {path}')
        # The median is visual center rather than the geometric bounding box edge.
        # This is an image anchor, NOT a collision coordinate.
        xxfoot=xx[yy>=y1-20]
        footx=round((x0+x1)/2,2) # alpha silhouette center, stable across differing ground foliage
        assets[f'{building}_{view}']={'bbox':[x0,y0,x1,y1], 'anchor_x':footx,'anchor_y':y1,
           'silhouette_h':y1-y0+1,'silhouette_w':x1-x0+1,
           'sha256':hashlib.sha256(path.read_bytes()).hexdigest()}
manifest={'schema':'mmai.r12.facade.technical-alignment.v1','status':'LAB_ONLY_NO_ART_APPROVAL',
  'method':'alpha>24 bbox, horizontal visual bounding center and lowest painted pixel; no repaint, no collision semantics',
  'source_revision':'R11','image_dimensions':[640,640], 'faces':assets}
dest=ROOT/'art_sources/R12_SILHOUETTE_ALIGNMENT.json';dest.write_text(json.dumps(manifest,indent=2,sort_keys=True)+'\n')
# Snapshot is imported by actual Canvas renderer; deterministic source+hash validation.
module=ROOT/'site/r12_asset_anchors.js'
module.write_text('/* AUTO-GENERATED by tools/measure_r12_facade_alignment.py; measurements, not paintings. */\n'
  '(function(root){\'use strict\';const data='+json.dumps(assets,separators=(',',':'),sort_keys=True)+';'
  'root.NSR12AssetAnchors=data;if(typeof module!==\'undefined\')module.exports=data;'
  '})(typeof globalThis!==\'undefined\'?globalThis:this);\n')
print(json.dumps({'status':'MEASURED_NOT_ART_APPROVED','faces':len(assets),'outfile':str(dest),'module':str(module)}))
