#!/usr/bin/env python3
"""Prepare, never approve, a genuine 3-building x 4-view painter's atlas.

Rows: cottage, forge, apothecary. Columns: quarter-turn views 0,90,180,270.
The INPUT must be an external PNG RGBA painted atlas with 3x4 equal cells.
No synthetic rotations, mirroring or geometry are generated by this tool.
The result ALWAYS requires an artist/author visual review and rights checks.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image
from fourview_inspector_r08 import inspect

BUILDINGS = [('1', 'cottage'), ('2', 'forge'), ('3', 'apothecary')]


def _unpack(sheet: Path):
    if sheet.suffix.lower() != '.png':
        raise ValueError('source must be a PNG atlas, not converted game art')
    with Image.open(sheet) as src:
        if src.mode != 'RGBA':
            raise ValueError('sheet must be RGBA with genuine transparent cutout cells')
        w, h = src.size
        if w % 4 or h % 3 or w // 4 < 128 or h // 3 < 128:
            raise ValueError('sheet must have four equal columns and three equal rows of >=128 pixels')
        cw, ch = w // 4, h // 3
        cells = []
        for row in range(3):
            for col in range(4):
                cell = src.crop((col*cw, row*ch, (col+1)*cw, (row+1)*ch)).copy()
                alpha = cell.getchannel('A')
                if alpha.getbbox() is None:
                    raise ValueError(f'empty painting at row={row}, view={col}')
                # More than a small margin must remain blank: safe cutout footprint.
                border = [alpha.crop((0, 0, cw, 4)), alpha.crop((0, ch-4, cw, ch)),
                          alpha.crop((0, 0, 4, ch)), alpha.crop((cw-4, 0, cw, ch))]
                if any(x.getextrema()[1] > 16 for x in border):
                    raise ValueError(f'cell crossing detected at row={row}, view={col}')
                cells.append(cell)
        return cells


def import_atlas(sheet: Path, output: Path, provenance: dict):
    """Write a candidate to a new empty folder. No game scene is modified."""
    sheet, output = Path(sheet), Path(output)
    if output.exists():
        raise FileExistsError('candidate destination already exists; overwrites are forbidden')
    if not isinstance(provenance, dict) or not provenance.get('origin') or not provenance.get('creator'):
        raise ValueError('creator and origin source evidence required; rights still unverified')
    cells = _unpack(sheet)
    output.mkdir(parents=True)
    entries = {}
    for i, (id_, name) in enumerate(BUILDINGS):
        faces, hashes = [], []
        for k in range(4):
            filename = f'r07_{name}_{k}'
            data = output / (filename + '.webp')
            cells[i*4+k].save(data, format='WEBP', lossless=True)
            faces.append(filename)
            hashes.append(hashlib.sha256(data.read_bytes()).hexdigest())
        entries[id_] = {
            'name': name, 'faces': faces, 'sha256': hashes,
            'license_checked': False, 'scale_anchor_reviewed': False,
            'source_atlas_sha256': hashlib.sha256(sheet.read_bytes()).hexdigest(),
            'source_cell_order': ['0','90','180','270'],
        }
    candidate = {
        'schema':'mmai.r08.fourview.atlas-candidate.v1',
        'state':'ART_CANDIDATE_UNREVIEWED',
        'origin':provenance,
        'buildings':entries,
        'art_quality_approved':False,
        'copyright_verified':False,
        'ready_for_game_render':False,
        'warning':'12 cutouts were COPIED from a source artwork; four coherent perspectives NOT proven. Owner must inspect each in gameplay.'
    }
    report = inspect(candidate, output)
    (output/'R08_CANDIDATE_MANIFEST.json').write_text(json.dumps(candidate,indent=2,ensure_ascii=False)+'\n')
    (output/'R08_INSPECTION.json').write_text(json.dumps(report,indent=2,ensure_ascii=False)+'\n')
    return report


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--sheet',required=True,type=Path)
    p.add_argument('--destination',required=True,type=Path)
    p.add_argument('--creator',required=True)
    p.add_argument('--origin',required=True)
    a=p.parse_args()
    print(json.dumps(import_atlas(a.sheet,a.destination,{'creator':a.creator,'origin':a.origin}),indent=2))


if __name__=='__main__':main()
